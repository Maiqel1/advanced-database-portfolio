\set ON_ERROR_STOP on
\set QUIET on
SET client_min_messages = warning;

DROP SCHEMA IF EXISTS tomiwa CASCADE;
CREATE SCHEMA tomiwa;
CREATE EXTENSION IF NOT EXISTS btree_gist SCHEMA public;
ALTER DATABASE hospital SET search_path = tomiwa, public;
SET search_path = tomiwa, public;

CREATE TABLE branch (
    branch_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL UNIQUE,
    state varchar(40) NOT NULL,
    address varchar(200) NOT NULL,
    consultation_fee numeric(10,2) NOT NULL CHECK (consultation_fee >= 0),
    opened_on date NOT NULL
);

CREATE TABLE staff (
    staff_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branch (branch_id),
    first_name varchar(60) NOT NULL,
    last_name varchar(60) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN (
        'receptionist', 'nurse', 'doctor', 'lab_scientist',
        'pharmacist', 'head_of_pharmacy', 'branch_manager')),
    phone varchar(20),
    hired_on date NOT NULL
);

CREATE TABLE patient (
    patient_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_number varchar(12) NOT NULL UNIQUE,
    first_name varchar(60) NOT NULL,
    last_name varchar(60) NOT NULL,
    date_of_birth date NOT NULL,
    sex char(1) NOT NULL CHECK (sex IN ('F', 'M')),
    phone varchar(20),
    address varchar(200),
    registered_branch_id integer NOT NULL REFERENCES branch (branch_id),
    registered_at timestamp NOT NULL,
    CHECK (date_of_birth <= registered_at::date)
);

CREATE TABLE portal_account (
    patient_id integer PRIMARY KEY REFERENCES patient (patient_id),
    username varchar(80) NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL,
    created_at timestamp NOT NULL
);

CREATE TABLE insurer (
    insurer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL UNIQUE,
    phone varchar(20)
);

CREATE TABLE insurance_policy (
    policy_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES patient (patient_id),
    insurer_id integer NOT NULL REFERENCES insurer (insurer_id),
    policy_number varchar(30) NOT NULL,
    valid_from date NOT NULL,
    valid_to date NOT NULL,
    CHECK (valid_to > valid_from),
    UNIQUE (insurer_id, policy_number),
    UNIQUE (policy_id, patient_id),
    CONSTRAINT insurance_policy_no_overlap
        EXCLUDE USING gist (patient_id WITH =, daterange(valid_from, valid_to, '[]') WITH &&)
);

CREATE TABLE appointment (
    appointment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES patient (patient_id),
    doctor_id integer NOT NULL REFERENCES staff (staff_id),
    branch_id integer NOT NULL REFERENCES branch (branch_id),
    scheduled_for timestamp NOT NULL,
    booked_via varchar(10) NOT NULL CHECK (booked_via IN ('reception', 'portal')),
    booked_by integer REFERENCES staff (staff_id),
    status varchar(10) NOT NULL CHECK (status IN ('booked', 'cancelled', 'attended', 'no_show')),
    CHECK ((booked_via = 'portal') = (booked_by IS NULL)),
    UNIQUE (appointment_id, patient_id)
);

CREATE UNIQUE INDEX appointment_no_double_booking
    ON appointment (doctor_id, scheduled_for)
    WHERE status <> 'cancelled';

CREATE TABLE visit (
    visit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES patient (patient_id),
    branch_id integer NOT NULL REFERENCES branch (branch_id),
    doctor_id integer NOT NULL REFERENCES staff (staff_id),
    appointment_id integer UNIQUE,
    policy_id integer,
    checked_in_by integer NOT NULL REFERENCES staff (staff_id),
    checked_in_at timestamp NOT NULL,
    status varchar(12) NOT NULL CHECK (status IN (
        'checked_in', 'with_nurse', 'with_doctor', 'at_lab', 'at_pharmacy', 'completed')),
    FOREIGN KEY (appointment_id, patient_id) REFERENCES appointment (appointment_id, patient_id),
    FOREIGN KEY (policy_id, patient_id) REFERENCES insurance_policy (policy_id, patient_id)
);

CREATE TABLE vital_signs (
    vitals_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES visit (visit_id),
    recorded_by integer NOT NULL REFERENCES staff (staff_id),
    recorded_at timestamp NOT NULL,
    temperature_c numeric(4,1) CHECK (temperature_c BETWEEN 30 AND 45),
    systolic_bp integer CHECK (systolic_bp BETWEEN 50 AND 260),
    diastolic_bp integer CHECK (diastolic_bp BETWEEN 30 AND 160),
    pulse_bpm integer CHECK (pulse_bpm BETWEEN 20 AND 250),
    weight_kg numeric(5,1) CHECK (weight_kg BETWEEN 0.5 AND 300),
    CHECK (systolic_bp > diastolic_bp)
);

CREATE TABLE clinical_note (
    note_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES visit (visit_id),
    written_by integer NOT NULL REFERENCES staff (staff_id),
    written_at timestamp NOT NULL,
    symptoms text,
    notes text,
    CHECK (symptoms IS NOT NULL OR notes IS NOT NULL)
);

CREATE TABLE diagnosis_code (
    icd10_code varchar(8) PRIMARY KEY,
    description varchar(200) NOT NULL
);

CREATE TABLE diagnosis (
    diagnosis_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES visit (visit_id),
    icd10_code varchar(8) NOT NULL REFERENCES diagnosis_code (icd10_code),
    made_by integer NOT NULL REFERENCES staff (staff_id),
    kind varchar(12) NOT NULL CHECK (kind IN ('provisional', 'final')),
    made_at timestamp NOT NULL
);

CREATE TABLE lab_test (
    test_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL UNIQUE,
    sample_type varchar(10) NOT NULL CHECK (sample_type IN ('blood', 'urine', 'stool')),
    price numeric(10,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE lab_test_parameter (
    parameter_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_id integer NOT NULL REFERENCES lab_test (test_id),
    name varchar(60) NOT NULL,
    unit varchar(20),
    normal_low numeric,
    normal_high numeric,
    UNIQUE (test_id, name),
    UNIQUE (test_id, parameter_id),
    CHECK (normal_low IS NULL OR normal_high IS NULL OR normal_low <= normal_high)
);

CREATE TABLE lab_order (
    lab_order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES visit (visit_id),
    ordered_by integer NOT NULL REFERENCES staff (staff_id),
    ordered_at timestamp NOT NULL
);

CREATE TABLE lab_order_item (
    lab_order_id integer NOT NULL REFERENCES lab_order (lab_order_id),
    test_id integer NOT NULL REFERENCES lab_test (test_id),
    performed_by integer REFERENCES staff (staff_id),
    completed_at timestamp,
    PRIMARY KEY (lab_order_id, test_id),
    CHECK ((performed_by IS NULL) = (completed_at IS NULL))
);

CREATE TABLE lab_result (
    lab_order_id integer NOT NULL,
    test_id integer NOT NULL,
    parameter_id integer NOT NULL,
    value_numeric numeric,
    value_text varchar(60),
    PRIMARY KEY (lab_order_id, test_id, parameter_id),
    FOREIGN KEY (lab_order_id, test_id) REFERENCES lab_order_item (lab_order_id, test_id),
    FOREIGN KEY (test_id, parameter_id) REFERENCES lab_test_parameter (test_id, parameter_id),
    CHECK (value_numeric IS NOT NULL OR value_text IS NOT NULL)
);

CREATE TABLE drug (
    drug_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL,
    form varchar(12) NOT NULL CHECK (form IN ('tablet', 'capsule', 'syrup', 'sachet', 'injection')),
    strength varchar(30) NOT NULL,
    unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (name, form, strength)
);

CREATE TABLE prescription (
    prescription_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES visit (visit_id),
    prescribed_by integer NOT NULL REFERENCES staff (staff_id),
    prescribed_at timestamp NOT NULL
);

CREATE TABLE prescription_item (
    prescription_id integer NOT NULL REFERENCES prescription (prescription_id),
    drug_id integer NOT NULL REFERENCES drug (drug_id),
    dose varchar(30) NOT NULL,
    frequency varchar(40) NOT NULL,
    duration_days integer NOT NULL CHECK (duration_days > 0),
    quantity integer NOT NULL CHECK (quantity > 0),
    instructions varchar(100),
    dispensed_by integer REFERENCES staff (staff_id),
    dispensed_at timestamp,
    PRIMARY KEY (prescription_id, drug_id),
    CHECK ((dispensed_by IS NULL) = (dispensed_at IS NULL))
);

CREATE TABLE branch_stock (
    branch_id integer NOT NULL REFERENCES branch (branch_id),
    drug_id integer NOT NULL REFERENCES drug (drug_id),
    quantity_in_stock integer NOT NULL CHECK (quantity_in_stock >= 0),
    reorder_level integer NOT NULL CHECK (reorder_level >= 0),
    PRIMARY KEY (branch_id, drug_id)
);

CREATE TABLE restock_request (
    request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL,
    drug_id integer NOT NULL,
    quantity_requested integer NOT NULL CHECK (quantity_requested > 0),
    requested_by integer NOT NULL REFERENCES staff (staff_id),
    requested_at timestamp NOT NULL,
    status varchar(10) NOT NULL CHECK (status IN ('pending', 'approved', 'rejected', 'received')),
    reviewed_by integer REFERENCES staff (staff_id),
    reviewed_at timestamp,
    FOREIGN KEY (branch_id, drug_id) REFERENCES branch_stock (branch_id, drug_id),
    CHECK ((status = 'pending') = (reviewed_by IS NULL)),
    CHECK ((reviewed_by IS NULL) = (reviewed_at IS NULL))
);

CREATE TABLE payment (
    payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_by integer NOT NULL REFERENCES staff (staff_id),
    received_at timestamp NOT NULL,
    method varchar(10) NOT NULL CHECK (method IN ('cash', 'transfer', 'card'))
);

CREATE TABLE charge (
    charge_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id integer NOT NULL REFERENCES visit (visit_id),
    charge_type varchar(12) NOT NULL CHECK (charge_type IN ('consultation', 'lab_test', 'drug')),
    lab_order_id integer,
    test_id integer,
    prescription_id integer,
    drug_id integer,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    payment_id integer REFERENCES payment (payment_id),
    FOREIGN KEY (lab_order_id, test_id) REFERENCES lab_order_item (lab_order_id, test_id),
    FOREIGN KEY (prescription_id, drug_id) REFERENCES prescription_item (prescription_id, drug_id),
    UNIQUE (lab_order_id, test_id),
    UNIQUE (prescription_id, drug_id),
    CONSTRAINT charge_links_match_type CHECK (
        (charge_type = 'consultation'
            AND lab_order_id IS NULL AND test_id IS NULL
            AND prescription_id IS NULL AND drug_id IS NULL)
        OR (charge_type = 'lab_test'
            AND lab_order_id IS NOT NULL AND test_id IS NOT NULL
            AND prescription_id IS NULL AND drug_id IS NULL)
        OR (charge_type = 'drug'
            AND prescription_id IS NOT NULL AND drug_id IS NOT NULL
            AND lab_order_id IS NULL AND test_id IS NULL)
    )
);

CREATE UNIQUE INDEX charge_one_consultation_per_visit
    ON charge (visit_id)
    WHERE charge_type = 'consultation';

CREATE FUNCTION check_staff_role() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    staff_ref integer;
    actual_role text;
BEGIN
    staff_ref := (to_jsonb(NEW) ->> TG_ARGV[0])::integer;
    IF staff_ref IS NULL THEN
        RETURN NEW;
    END IF;
    SELECT role INTO actual_role FROM staff WHERE staff_id = staff_ref;
    IF NOT FOUND THEN
        RETURN NEW;
    END IF;
    IF NOT actual_role = ANY (TG_ARGV[1:]) THEN
        RAISE EXCEPTION '%.% must be a %, but staff member % is a %',
            TG_TABLE_NAME, TG_ARGV[0], array_to_string(TG_ARGV[1:], ' or '), staff_ref, actual_role
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

